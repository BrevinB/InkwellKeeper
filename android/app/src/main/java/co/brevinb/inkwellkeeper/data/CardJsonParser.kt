package co.brevinb.inkwellkeeper.data

import co.brevinb.inkwellkeeper.model.CardRarity
import co.brevinb.inkwellkeeper.model.CardVariant
import co.brevinb.inkwellkeeper.model.LorcanaCard
import co.brevinb.inkwellkeeper.model.LorcanaSet
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.booleanOrNull
import kotlinx.serialization.json.doubleOrNull
import kotlinx.serialization.json.intOrNull
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject

/**
 * Decodes the bundled catalog JSON. Like the iOS decoder it accepts several key spellings per
 * field (the catalog has been generated by different scripts over time) and generates an id
 * when a card has none.
 */
object CardJsonParser {
    private val json = Json { ignoreUnknownKeys = true; isLenient = true }

    fun parseSets(text: String): List<LorcanaSet> {
        val root = json.parseToJsonElement(text).jsonObject
        val sets = root["sets"]?.jsonArray ?: return emptyList()
        return sets.mapNotNull { element ->
            val obj = element as? JsonObject ?: return@mapNotNull null
            LorcanaSet(
                id = obj.string("id") ?: return@mapNotNull null,
                name = obj.string("name") ?: return@mapNotNull null,
                setCode = obj.string("setCode") ?: "",
                setNumber = obj.string("setNumber"),
                releaseDate = obj.string("releaseDate"),
                cardCount = obj.int("cardCount") ?: 0,
                description = obj.string("description") ?: "",
                isReleased = obj.bool("isReleased") ?: true,
            )
        }
    }

    fun parseSetCards(text: String): List<LorcanaCard> {
        val root = json.parseToJsonElement(text).jsonObject
        val cards = root["cards"] as? JsonArray ?: return emptyList()
        return cards.mapNotNull { (it as? JsonObject)?.let(::parseCard) }
    }

    fun parseCard(obj: JsonObject): LorcanaCard? {
        val name = obj.string("name", "Name") ?: return null
        val cost = obj.int("cost", "Cost") ?: return null
        val type = obj.string("type", "Type") ?: return null
        val rarity = CardRarity.fromString(obj.string("rarity", "Rarity") ?: return null)
        val setName = obj.string("setName", "Set_Name", "set_name", "set") ?: return null
        val imageUrl = obj.string("imageUrl", "Image", "image_url", "image") ?: return null
        val variant = CardVariant.fromRawOrNormal(obj.string("variant", "Variant"))
        val cardNumber = obj.int("cardNumber", "Card_Num", "card_number", "number")
        val id = obj.string("id", "ID") ?: LorcanaCard.generatedId(setName, cardNumber, variant, name)
        return LorcanaCard(
            id = id,
            name = name,
            cost = cost,
            type = type,
            rarity = rarity,
            setName = setName,
            cardText = obj.string("cardText", "Body_Text", "text", "card_text") ?: "",
            imageUrl = imageUrl,
            price = obj.double("price", "Price"),
            variant = variant,
            cardNumber = cardNumber,
            uniqueId = obj.string("uniqueId", "Unique_ID", "unique_id"),
            inkwell = obj.bool("inkwell", "Inkwell", "Inkable", "inkable"),
            strength = obj.int("strength", "Strength"),
            willpower = obj.int("willpower", "Willpower"),
            lore = obj.int("lore", "Lore"),
            franchise = obj.string("franchise", "Franchise"),
            inkColor = obj.string("Color", "inkColor", "Ink_Color", "ink_color"),
        )
    }

    private fun JsonObject.primitive(vararg keys: String): JsonPrimitive? {
        for (key in keys) {
            val value: JsonElement? = this[key]
            if (value is JsonPrimitive && value !is JsonNull) return value
        }
        return null
    }

    private fun JsonObject.string(vararg keys: String): String? {
        for (key in keys) {
            val value = this[key] as? JsonPrimitive ?: continue
            if (value is JsonNull || !value.isString) continue
            return value.content
        }
        return null
    }

    private fun JsonObject.int(vararg keys: String): Int? {
        for (key in keys) {
            val value = this[key] as? JsonPrimitive ?: continue
            if (value is JsonNull || value.isString) continue
            value.intOrNull?.let { return it }
            value.doubleOrNull?.let { return it.toInt() }
        }
        return null
    }

    private fun JsonObject.double(vararg keys: String): Double? =
        primitive(*keys)?.takeIf { !it.isString }?.doubleOrNull

    private fun JsonObject.bool(vararg keys: String): Boolean? {
        for (key in keys) {
            val value = this[key] as? JsonPrimitive ?: continue
            if (value is JsonNull || value.isString) continue
            value.booleanOrNull?.let { return it }
        }
        return null
    }
}
