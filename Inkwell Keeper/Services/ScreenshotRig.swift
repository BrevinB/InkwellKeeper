//
//  ScreenshotRig.swift
//  Inkwell Keeper
//
//  Filming rig: launch arguments that open screens which otherwise need taps, so
//  App Store screenshots can be captured on simulators whose display can't be
//  driven (like the unfolded iPhone Duo). Pairs with DemoCollectionSeeder.
//
//      -demoAIDeck YES         Decks: builds a deck with the real AI Deck Builder
//                              (once) and opens it.
//      -rulesQuestion "…"      Rules: asks this question when the assistant is ready.
//      -demoImport YES         Collection: opens Bulk Import and imports a Dreamborn
//                              CSV made from the current collection.
//

#if DEBUG && targetEnvironment(simulator)
import Foundation

@MainActor
enum ScreenshotRig {
    private static let demoDeckName = "Amber Steel Aggro"

    static var rulesQuestion: String? {
        UserDefaults.standard.string(forKey: "rulesQuestion")
    }

    static var opensDemoImport: Bool {
        UserDefaults.standard.bool(forKey: "demoImport")
    }

    /// A Dreamborn export of part of the collection, so the import screen has a real
    /// file's worth of cards to work through.
    static func demoImportCSV(from cards: [LorcanaCard]) -> String {
        let entries = cards.prefix(640).enumerated().map { index, card in
            (card: card, quantity: index % 5 == 0 ? 2 : 1)
        }
        return ImportService.shared.exportDreambornCSV(entries)
    }

    /// The demo deck, generated by the AI Deck Builder the first time it's asked for.
    static func demoAIDeck(deckManager: DeckManager) async -> Deck? {
        guard UserDefaults.standard.bool(forKey: "demoAIDeck") else { return nil }
        if let existing = deckManager.decks.first(where: { $0.name == demoDeckName }) {
            return existing
        }

        let service = AIDeckService.shared
        service.checkAvailability()
        for _ in 0..<40 where service.availability == .checking {
            try? await Task.sleep(for: .milliseconds(250))
        }
        guard service.availability == .available else {
            print("IWK-RIG: AI deck builder unavailable (\(service.availability))")
            return nil
        }

        print("IWK-RIG: generating demo AI deck")
        await service.generateDeck(
            description: "A fast aggro deck that wins by questing with low-cost characters",
            format: .coreConstructed,
            inkColors: [.amber, .steel],
            archetype: .aggro
        )
        guard service.matchedCount > 0 else {
            print("IWK-RIG: AI deck generation failed: \(service.errorMessage ?? "no cards")")
            return nil
        }

        let deck = deckManager.createDeck(
            name: demoDeckName,
            description: "A fast aggro deck that wins by questing with low-cost characters",
            format: .coreConstructed,
            inkColors: [.amber, .steel],
            archetype: .aggro
        )
        service.applySuggestions(to: deck, deckManager: deckManager)
        deckManager.updateDeckColorsFromCards(deck)
        service.reset()
        print("IWK-RIG: demo AI deck has \(deck.totalCards) cards")
        return deck
    }
}
#endif
